/**
 * Calculate statutory escalation, fines and late fees for any delay
 * @param {Object} options
 * @param {number} options.delayDays - number of days return is delayed past due date (20th)
 * @param {boolean} options.isNil - whether it is a Nil return
 * @param {number} options.netTaxLiability - unpaid net tax liability in Rupees
 */
export function calculateDelayEscalation({ delayDays = 0, isNil = false, netTaxLiability = 70200 } = {}) {
  const days = Math.max(0, parseInt(delayDays, 10) || 0);
  const tax = Math.max(0, parseFloat(netTaxLiability) || 0);

  // Section 47 Late fee rate per day
  // Normal: ₹25 CGST + ₹25 SGST = ₹50/day (Capped at ₹10,000 statutory limit)
  // Nil: ₹10 CGST + ₹10 SGST = ₹20/day (Capped at ₹10,000 statutory limit)
  const dailyFeeRate = isNil ? 20 : 50;
  const rawLateFee = days * dailyFeeRate;
  const statutoryLateFee = Math.min(10000, rawLateFee);

  // Section 50 Interest @ 18% p.a. on cash tax liability
  const interestRatePerAnnum = 0.18;
  const rawInterest = isNil ? 0 : Math.round((tax * interestRatePerAnnum * days) / 365);

  const totalEscalationFine = statutoryLateFee + rawInterest;

  // Rule 138E E-Way Bill blocking if delayed > 60 days
  const ewayBillBlocked = days >= 60;

  let riskTier = "ON_TIME";
  let advisoryMessage = "You are filing on time. ₹0 penalty and 100% compliant.";
  let badgeColor = "#10B981";

  if (days > 0 && days <= 5) {
    riskTier = "LOW_PENALTY";
    advisoryMessage = `Filing delayed by ${days} day(s). Late fee of ₹${statutoryLateFee} plus ₹${rawInterest} interest applies. File immediately to stop escalation.`;
    badgeColor = "#F59E0B";
  } else if (days > 5 && days <= 30) {
    riskTier = "MODERATE_ESCALATION";
    advisoryMessage = `Filing delayed by ${days} days. Total penalty has grown to ₹${totalEscalationFine.toLocaleString("en-IN")}. Daily fine increases by ₹${dailyFeeRate}/day.`;
    badgeColor = "#EA580C";
  } else if (days > 30) {
    riskTier = "SEVERE_ESCALATION";
    advisoryMessage = ewayBillBlocked
      ? `CRITICAL RISK: Delayed by ${days} days! E-Way Bill generation is BLOCKED under Rule 138E. Total fine: ₹${totalEscalationFine.toLocaleString("en-IN")}.`
      : `HIGH RISK: Delayed by ${days} days. Total penalty is ₹${totalEscalationFine.toLocaleString("en-IN")}. Immediate filing required to avoid bank account freeze notice.`;
    badgeColor = "#DC2626";
  }

  return {
    success: true,
    delayDays: days,
    isNil,
    netTaxLiability: tax,
    statutoryLateFee,
    statutoryInterest: rawInterest,
    totalEscalationFine,
    dailyAccrualRate: dailyFeeRate,
    ewayBillBlocked,
    riskTier,
    badgeColor,
    advisoryMessage,
    statutoryReferences: {
      lateFeeSection: "Section 47 of CGST Act",
      interestSection: "Section 50(1) of CGST Act @ 18% p.a.",
      blockingRule: "Rule 138E of CGST Rules (E-Way Bill restriction for 2 months default)"
    }
  };
}

/**
 * Returns full cadence notification sequence with live simulated payloads
 */
export function getCadenceSchedule(currentDay = 7) {
  return STATUTORY_SEQUENCE.map(step => {
    const isPast = step.dayOfMonth < currentDay;
    const isCurrent = step.dayOfMonth === currentDay;
    return {
      ...step,
      isPast,
      isCurrent,
      status: isCurrent ? "ACTIVE_NOW" : isPast ? "COMPLETED" : "UPCOMING"
    };
  });
}

